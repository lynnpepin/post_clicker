/// Game dt loop
function update(dt) {
  // dt in ms; around 125
  // console.log(dt); very close to 125
  //location.reload();

  // Increase likes and reposts
  for (var ii = 0; ii < posted_posts.length ; ii ++) {
    // Asymptote toward followers, faster by num reposts
    delta_likes(
      ii,
      Math.random() * Math.min(get_reposts(ii) * followers * 2**(-32), 1.0) // rate, slow
      * get_likes(ii) * (1 - get_likes(ii) / (followers + 1)) // // logistic equation
      * dt / 1000
      + dt / 1000_000
    )
    // Asymptote toward population, faster by num reposts
    delta_reposts(
      ii,
      Math.random() * (followers/world_population) * 2**(-32)// rate, slow
      * get_reposts(ii) * (1 - get_reposts(ii)/world_population) // logistic equation
      * dt / 1000
    )

    
  }

  // Increase genius by ego
  delta_genius(
    ego_value * dt / 1000
  );


  // Increase ego as function of current followers
  delta_ego(
    followers * dt / 1000_000
  );
  
  // Increase followers: df/dt (total likes, reposts) toward population
  delta_followers(
    Math.random() * Math.min(2**(-32) * sum_reposts * sum_likes * posted_posts.length, 2**(-16)) // rate
    * followers * (1 - followers / world_population)// logistic equation
    * dt / 1000
  )

  // Early game boost
  if (followers <= 67621) {
    if (posted_posts.length >= 6) {
      delta_followers(Math.random() * dt * posted_posts.length / 100_000);
    }
  }
  if (posted_posts.length < 20) {
    if (Math.random() < (dt * followers / 10_000)) {
      var ii = Math.floor(Math.random() * posted_posts.length);
      delta_reposts(ii, 1);
      delta_likes(ii, 1);
    }
  }

  delta_population((Math.random() * 16 - 2) * dt / 1000);

  // posts accumulate likes asymptoting toward followers as function of reblogs, followers + random
  // posts accumulate reblogs asymptoting toward population as function of likes, population + randomly
}

