/// Typing posts
function type_post() {
  //print_debug("type_post()");
  if (target_post.length > 0) {
    document.getElementById("post_box").style.opacity = "1";
    // Still have post to type!
    draft_post = draft_post + target_post.slice(0, 1);
    target_post = target_post.slice(1); 

    set_post_input(draft_post);

    set_post_pie_percent(100 * (draft_post.length / target_post_length))

    // Hack to expand postbox as needed
    const ta = document.getElementById('post_input');
    ta.style.height = ta.scrollHeight + 'px';

    set_genius_max(Math.floor(genius_max * 1.001) + (genius_max <= 10 ? 1 : 0));
    return true;
  }
  else {
    // Can't type; post is ready to go
    return false;
  }
}

function set_post_input(value) {
  document.getElementById('post_input').value = value;
  if (draft_post.length == target_post_length) {
    document.getElementById('post_send').disabled = false;
  }
}

function set_post_pie_percent(percent) {
  post_pie = document.getElementById('post_pie');
  degree = percent * 360.0 / 100 + 2;
  color = (percent >= 100.0) ? "#2d4" : "#38d";
  othercolor = (percent >= 100.0) ? "#2d4" : "#0000";
  post_pie.style.backgroundImage =
    `conic-gradient(${color} ${degree}deg, ${othercolor} ${degree}deg 360deg)`;
}

/// Creating new posts
function post_send() {
  if (draft_post.length == target_post_length) {
    // Create the post!
    create_post(draft_post);
    // Update ego
    delta_ego(1);

    // Reset the type box
    target_post = raw_posts.shift();
    target_post_length = target_post.length;
    draft_post = "";
    set_post_pie_percent(0);
    set_post_input("");
    // Re-disable post
    document.getElementById('post_send').disabled = true;
    // Re-set height
    const ta = document.getElementById('post_input');
    ta.style.height = 'auto';
    set_genius_max( Math.floor(genius_max * 1.001) + (genius_max <= 1000 ? 5 : 0) );
    
    // Slowly reveal elements
    if (posted_posts.length == 4) {
      document.getElementById("followers_container").style.opacity = "1";
    }
    if (posted_posts.length == 2) {
      document.getElementById("ego_container").style.opacity = "1";
    }
    if (posted_posts.length == 16) {
      document.getElementById("population_container").style.opacity = "1";
    }
  }

  //print_debug("post_send()");
}

function create_post(post_text) {
  // Get the template
  post_template = document.getElementById("post_template");
  new_post = post_template.content.cloneNode(true);

  // Get the container we want to put it in
  post_feed = document.getElementById("post_feed");

  // Put everything together
  new_post.querySelector(".post_text").textContent = post_text;
  post_feed.prepend(new_post);

  // Also add it to my posted_posts
  posted_posts.push(new_post);
  posted_posts_likes.push(0);
  posted_posts_reposts.push(0);

  // More genius per click
  delta_genius_per_click(1);
}

